"""Tempest 2000 symbol map from mwenge's build (reference/tempest2k/symout/yak.cof).

python -I tools/t2k_symbols.py [--out logs/t2k_symbols.txt] [--check] [name ...]

The owner's ROM (Tempest 2000 (1994).jag, md5 602bc995...) is byte-identical to mwenge's rebuilt cartridge, so his
link addresses are real addresses: rln -a 802000 4000 efa8 (text at $802000). yak.cof is a COFF / BSD-style object
from rmac -fb: its symbol table gives every label with its section. Prints name, address, section.
--check: compare the first bytes at each text label in the ROM with the listing (yak.lst) to prove the map.
"""
import os
import re
import struct
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
REF = os.path.join(ROOT, 'reference', 'tempest2k')
COF = os.path.join(REF, 'symout', 'yak.cof')
LST = os.path.join(REF, 'symout', 'yak.lst')
ROM = os.path.join(ROOT, 'Tempest 2000 (1994).jag')


def read_aout(data):
    """rmac -fb writes BSD a.out (big-endian): magic, text, data, bss, syms, entry, trsize, drsize."""
    magic, tsz, dsz, bsz, ssz, entry, trs, drs = struct.unpack('>8I', data[:32])
    return dict(magic=magic, text=tsz, data=dsz, bss=bsz, syms=ssz, trsize=trs, drsize=drs)


def symbols():
    data = open(COF, 'rb').read()
    h = read_aout(data)
    off = 32 + h['text'] + h['data'] + h['trsize'] + h['drsize']
    strtab = off + h['syms']
    out = []
    for i in range(h['syms'] // 12):
        sx, typ, other, desc, val = struct.unpack('>IBbhI', data[off + i * 12: off + i * 12 + 12])
        end = data.index(b'\0', strtab + sx)
        name = data[strtab + sx:end].decode('latin-1')
        out.append((name, typ, val))
    return h, out


TEXT, DATA, BSS = 0x802000, 0x4000, 0xEFA8   # rln -a 802000 4000 efa8 (checked: sync $E366, modnum $EA06 in ROM code)


def relocate(h, typ, val):
    """Object offsets run text, data, bss back to back; the link puts them at TEXT / DATA / BSS."""
    t = typ & 0x1e
    if t == 0x04:
        return TEXT + val, 'text'
    if t == 0x06:
        return DATA + val - h['text'], 'data'
    if t == 0x08:
        return BSS + val - h['text'] - h['data'], 'bss'
    return val, 'abs'


def symbol_map():
    """name -> (address, section) for every label / variable / equate."""
    h, syms = symbols()
    return {n: relocate(h, t, v) for n, t, v in syms if t & 0x1e}


def main():
    h, syms = symbols()
    syms = [(n, t, v) for n, t, v in syms if t & 0x1e]   # (undefined / external: gpurun lives in yakgpu.s)
    print(f"a.out: text {h['text']:#x} data {h['data']:#x} bss {h['bss']:#x} syms {len(syms)}", file=sys.stderr)
    kinds = {}
    for _, typ, _ in syms:
        kinds[typ & 0x1e] = kinds.get(typ & 0x1e, 0) + 1
    print('type counts', {hex(k): v for k, v in sorted(kinds.items())}, file=sys.stderr)
    names = [a for a in sys.argv[1:] if not a.startswith('--')]
    for name, typ, val in syms:
        if name in names:
            a, sec = relocate(h, typ, val)
            print(f'{name:28s} ${a:06X} {sec}')
    if '--out' in sys.argv:
        path = sys.argv[sys.argv.index('--out') + 1]
        names.remove(path) if path in names else None
        with open(path, 'w') as f:
            for a, sec, name in sorted((*relocate(h, t, v), n) for n, t, v in syms):
                f.write(f'{a:06X} {sec:4s} {name}\n')
        print('wrote', path, file=sys.stderr)
    if '--header' in sys.argv:
        write_header(h, syms, sys.argv[sys.argv.index('--header') + 1])
    if '--callers' in sys.argv:
        for label in sys.argv[sys.argv.index('--callers') + 1].split(','):
            for ret, word, line in callers(label):
                print(f'{label}: return ${ret:06X} word ${word:04X}  (yak.s {line})')


CPP_KEYWORDS = {'and', 'or', 'not', 'xor', 'int', 'char', 'new', 'delete', 'this', 'do', 'if', 'for', 'case',
                'default', 'register', 'short', 'long', 'float', 'double', 'goto', 'return', 'switch', 'while',
                'union', 'struct', 'class', 'const', 'auto', 'signed', 'unsigned', 'void', 'volatile', 'static',
                'extern', 'inline', 'friend', 'virtual', 'public', 'private', 'protected', 'template', 'typename',
                'using', 'namespace', 'operator', 'try', 'catch', 'throw', 'bool', 'true', 'false', 'enum', 'else',
                'break', 'continue', 'sizeof', 'typedef', 'export', 'asm', 'compl', 'bitand', 'bitor', 'not_eq'}


def write_header(h, syms, path):
    """Every symbol as a constexpr address (C++ keywords get a trailing _)."""
    rows = sorted((*relocate(h, t, v), n) for n, t, v in syms)
    with open(path, 'w', newline='\n') as f:
        f.write('// t2k_symbols.h - GENERATED by tools/t2k_symbols.py --header (do not edit). Every label, variable and\n'
                '// equate of Tempest 2000\'s yak.s at its address in the retail cartridge (md5 602bc995...): text at\n'
                '// $802000 (ROM), data at $4000 and bss at $EFA8 (RAM). Source: reference/tempest2k/symout/yak.cof.\n'
                '#pragma once\n#include <cstdint>\n\nnamespace t2ksym {\n')
        for a, sec, name in rows:
            f.write(f'constexpr uint32_t {name}{"_" if name in CPP_KEYWORDS else ""} = 0x{a:06X};   // {sec}\n')
        f.write('}  // namespace t2ksym\n')
    print('wrote', path, len(rows), 'symbols', file=sys.stderr)


def callers(label):
    """The return address after every bsr / jsr to label (from yak.lst), with the ROM's opcode word there."""
    rom = open(ROM, 'rb').read()
    pat = re.compile(r'^\s*(\d+)\s+([0-9A-F]{8})\s+([0-9A-Fx]+)\s+(?:\S+:)?\s*(?:bsr|jsr)(?:\.[swl])?\s+' +
                     re.escape(label) + r'\b')
    out = []
    for ln in open(LST, encoding='latin-1'):
        m = pat.match(ln)
        if not m or int(m.group(2), 16) >= 0x18398:
            continue
        ret = TEXT + int(m.group(2), 16) + len(m.group(3)) // 2
        word = int.from_bytes(rom[ret - 0x800000: ret - 0x800000 + 2], 'big')
        out.append((ret, word, int(m.group(1))))
    return out


if __name__ == '__main__':
    main()
