"""Draws the program icon: an original claw ship (Tempest's player ship, drawn here, not game artwork) on a navy badge
with web lanes behind it -> res/t2k.ico (16-256), res/icon_rgba.h (64 x 64 RGBA for the window icon) and a preview
res/icon.png.
usage: python -I tools/make_icon.py"""
import os
from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
S = 1024   # drawn large, then scaled down


def draw():
    im = Image.new('RGBA', (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    # badge
    d.ellipse((24, 24, S - 24, S - 24), fill=(10, 14, 48, 255), outline=(60, 90, 255, 255), width=28)
    # web lanes converging above the centre
    cx, cy = S * 0.5, S * 0.30
    lanes = Image.new('RGBA', (S, S), (0, 0, 0, 0))
    ld = ImageDraw.Draw(lanes)
    for k in range(-4, 5):
        x = S * 0.5 + k * S * 0.16
        ld.line((cx + k * S * 0.03, cy, x, S * 0.98), fill=(40, 70, 230, 255), width=14)
    ld.ellipse((cx - S * 0.13, cy - S * 0.05, cx + S * 0.13, cy + S * 0.05), outline=(40, 70, 230, 255), width=12)
    mask = Image.new('L', (S, S), 0)
    ImageDraw.Draw(mask).ellipse((52, 52, S - 52, S - 52), fill=255)
    im.paste(lanes, (0, 0), Image.composite(lanes, Image.new('RGBA', (S, S)), mask).split()[3])
    # the claw: two prongs joined at the bottom (Tempest's ship), yellow to orange
    pts = [(0.20, 0.30), (0.12, 0.66), (0.50, 0.90), (0.88, 0.66), (0.80, 0.30),
           (0.67, 0.60), (0.50, 0.71), (0.33, 0.60)]
    poly = [(x * S, y * S) for x, y in pts]
    claw = Image.new('RGBA', (S, S), (0, 0, 0, 0))
    grad = Image.new('RGBA', (S, S))
    gd = ImageDraw.Draw(grad)
    for y in range(S):
        t = min(1.0, max(0.0, (y / S - 0.3) / 0.6))
        gd.line((0, y, S, y), fill=(255, int(240 - 120 * t), int(60 - 50 * t), 255))
    m = Image.new('L', (S, S), 0)
    ImageDraw.Draw(m).polygon(poly, fill=255)
    claw.paste(grad, (0, 0), m)
    # a dark rim and a soft glow behind
    glow = Image.new('RGBA', (S, S), (0, 0, 0, 0))
    ImageDraw.Draw(glow).polygon(poly, fill=(255, 200, 40, 160))
    glow = glow.filter(ImageFilter.GaussianBlur(26))
    im = Image.alpha_composite(im, glow)
    im = Image.alpha_composite(im, claw)
    ImageDraw.Draw(im).polygon(poly, outline=(120, 50, 0, 255), width=10)
    return im


def main():
    os.makedirs(os.path.join(ROOT, 'res'), exist_ok=True)
    big = draw()
    sizes = [16, 24, 32, 48, 64, 128, 256]
    icons = [big.resize((n, n), Image.LANCZOS) for n in sizes]
    icons[-1].save(os.path.join(ROOT, 'res', 't2k.ico'), sizes=[(n, n) for n in sizes], append_images=icons[:-1])
    big.resize((256, 256), Image.LANCZOS).save(os.path.join(ROOT, 'res', 'icon.png'))
    px = big.resize((64, 64), Image.LANCZOS).tobytes()
    with open(os.path.join(ROOT, 'res', 'icon_rgba.h'), 'w') as f:
        f.write('// Generated by tools/make_icon.py: the window icon, 64 x 64 RGBA. Do not edit.\n')
        f.write('static const unsigned char k_icon_rgba[64 * 64 * 4] = {\n')
        for k in range(0, len(px), 24):
            f.write('  ' + ', '.join(str(b) for b in px[k:k + 24]) + ',\n')
        f.write('};\n')
    print('res/t2k.ico, res/icon_rgba.h, res/icon.png')


if __name__ == '__main__':
    main()
