"""Generate C++ for an AOT module from a core dump (t3k.exe --aotdump=... -> nuance_aot_dump).

python -I tools/t3k_aot.py <dump.txt> <out.cpp>

The output runs each packet the way Nuance's interpreter does (FetchDecodeExecute's interpreted path +
MPE::ExecuteNuances), calling the same Execute_* handlers directly with the decoded fields as constants. Fields
that point into the decoding MPE's local memory (D+offset) are rebuilt per MPE in Bind(). INFO fields that hold
host pointers are stale scheduler data (only the bilinear MEM handlers read INFO, and the decoder sets theirs): 0.
The output is a translation of game code: write it outside the repositories (build_aot/).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'third_party', 'NuanceResurrection', 'src')

PACKETINFO_NOP = 0x00000001
PACKETINFO_BREAKPOINT = 0x00000002
PACKETINFO_DEPENDENCY_PRESENT = 0x00000080


def handler_names():
    s = open(os.path.join(SRC, 'mpe.cpp'), encoding='utf-8').read()
    i = s.index('const NuanceHandler nuanceHandlers[] =')
    body = re.sub(r'//[^\n]*', '', s[s.index('{', i) + 1:s.index('};', i)])
    return [x.strip() for x in body.split(',') if x.strip()]


def parse_field(tok, field_index):
    """-> (value text for the constant table, fixup offset or None)."""
    if tok.startswith('D+'):
        return '0', ('D', int(tok[2:], 16))
    if tok.startswith('E+') and field_index != 1:   # a fixed place in nuonEnv (e.g. another MPE's memory)
        return '0', ('E', int(tok[2:], 16))
    if tok.startswith(('M+', 'E+', '?')):
        raw = tok[1:] if tok.startswith('?') else None
        if field_index == 1:   # INFO: stale host pointer
            return '0', None
        if raw is None:
            raise SystemExit('pointer into the MPE / environment outside INFO: %s' % tok)
        return '0x%sULL' % raw, None
    return '0x%sULL' % tok, None


def main():
    dump, out = sys.argv[1], sys.argv[2]
    names = handler_names()
    lines = open(dump).read().split('\n')
    head = lines[0].split()
    src, length, base = int(head[1], 16), int(head[2]), int(head[3], 16)
    packets = []   # (pc, pcroute, info, [(handler, [5 values], [fixups])])
    cur = None
    for ln in lines[1:]:
        p = ln.split()
        if not p:
            continue
        if p[0] == 'P':
            cur = [int(p[1], 16), int(p[2], 16), int(p[3], 16), []]
            packets.append(cur)
        elif p[0] == 'N':
            h = int(p[1])
            vals, fix = [], []
            for fi, tok in enumerate(p[2:7]):
                v, off = parse_field(tok, fi)
                vals.append(v)
                if off is not None:
                    fix.append((fi, off))
            cur[3].append((h, vals, fix))

    # The module's bytes, from the system-bus copy the dump was made from (written next to the dump).
    code = open(dump.replace('.txt', '.bin'), 'rb').read() if os.path.exists(dump.replace('.txt', '.bin')) else None
    if code is None or len(code) != length:
        raise SystemExit('need %s with the module bytes (%d)' % (dump.replace('.txt', '.bin'), length))

    tag = '%08X' % src
    o = []
    o.append('// Generated by tools/t3k_aot.py from %s - a translation of game code: do not commit.' % os.path.basename(dump))
    o.append('// Module $%s (%d bytes) loaded at $%08X, %d packets.' % (tag, length, base, len(packets)))
    o.append('#include <cstring>')
    o.append('#include "mpe.h"')
    o.append('#define AOT_NEED_INTERRUPT_TEST')
    o.append('#include "aot.h"')
    for h in ('ExecuteALU.h', 'ExecuteECU.h', 'ExecuteMEM.h', 'ExecuteMisc.h', 'ExecuteMUL.h', 'ExecuteRCU.h'):
        o.append('#include "%s"' % h)
    o.append('')
    o.append('#include "NuonEnvironment.h"')
    o.append('extern NuonEnvironment nuonEnv;')
    o.append('extern uint32 g_mediaQueued[4];')
    o.append('extern uint64 s_tickCounter[4];')
    o.append('void TickMediaCallbacks(MPE& mpe);')
    o.append('')
    o.append('namespace {')
    o.append('')
    o.append('const uint8 kCode[%d] = {' % length)
    for i in range(0, length, 32):
        o.append('  ' + ','.join('0x%02X' % b for b in code[i:i + 32]) + ',')
    o.append('};')
    nuances = []
    fixups = []
    for pk in packets:
        for h, vals, fix in pk[3]:
            k = len(nuances)
            nuances.append(vals)
            for fi, off in fix:
                fixups.append((k, fi, off))
    o.append('')
    for k, vals in enumerate(nuances):
        o.append('constexpr Nuance kN%d = {{%s}};' % (k, ', '.join(vals)))
    fix_by_nuance = {}
    for k, fi, off in fixups:
        fix_by_nuance.setdefault(k, []).append((fi, off))
    o.append('')
    o.append('void Bind(MPE&) {}')
    o.append('')
    # Run: a dispatch switch on entry, then the packets as straight-line code that falls through to the next
    # packet; per packet only the delay-slot countdown, the exception check and "did we jump". Once per block (at
    # done): the media tick and Halt, as for one of Nuance's compiled blocks. The block ends at a taken jump or
    # after maxPackets.
    o.append('uint32 Run(MPE& m, const uint32 maxPackets)')
    o.append('{')
    o.append('  const uint32 idx = m.mpeIndex;')
    o.append('  uint32 n = 0;')
    o.append('dispatch:')
    o.append('  switch(m.pcexec)')
    o.append('  {')
    for pc, route, info, nus in packets:
        o.append('    case 0x%08XU: goto L_%08X;' % (pc, pc))
    o.append('    default: goto done;')
    o.append('  }')
    pcs = [pk[0] for pk in packets]
    k = 0
    for j, (pc, route, info, nus) in enumerate(packets):
        o.append('L_%08X:' % pc)
        if info & PACKETINFO_BREAKPOINT:
            o.append('  goto done;')
            k += len(nus)
            continue
        o.append('  m.pcroute = 0x%08XU; m.pcexec = 0x%08XU;' % (route, route))
        if not (info & PACKETINFO_NOP):
            if info & PACKETINFO_DEPENDENCY_PRESENT:
                o.append('  memcpy(m.tempreg_union, m.reg_union, sizeof(uint32) * 48);')
                regs = 'm.tempreg_union'
            else:
                o.append('  m.tempCC = m.cc;')
                regs = 'm.reg_union'
            for h, vals, fix in nus:
                if k in fix_by_nuance:   # a pointer: this MPE's own local memory, or a fixed place in nuonEnv
                    o.append('  { Nuance t = kN%d;' % k)
                    for fi, (kind, off) in fix_by_nuance[k]:
                        if kind == 'D':
                            o.append('    t.fields[%d] = (size_t)&m.dtrom[0x%X];' % (fi, off))
                        else:
                            o.append('    t.fields[%d] = (size_t)((uint8*)&nuonEnv + 0x%X);' % (fi, off))
                    o.append('    %s(m, %s, t); }' % (names[h], regs))
                else:
                    o.append('  %s(m, %s, kN%d);' % (names[h], regs, k))
                k += 1
        else:
            k += len(nus)
        o.append('  ++n;')
        o.append('  if(m.ecuSkipCounter != 0 && --m.ecuSkipCounter == 0) m.pcexec = m.pcfetchnext;')
        o.append('  if((m.excephalten & m.excepsrc) || (m.pcexec != 0x%08XU) || (n >= maxPackets)) goto done;' % route)
        nxt = pcs[j + 1] if j + 1 < len(pcs) else None
        if nxt != route:
            o.append('  goto dispatch;')
    o.append('done:')
    o.append('  if(n)')
    o.append('  {')
    o.append('    if(!(m.excephalten & m.excepsrc) && (m.mpectl & MPECTRL_MPEGO))')
    o.append('    {')
    o.append('      if(g_mediaQueued[idx] == 0) ++s_tickCounter[idx];')
    o.append('      else TickMediaCallbacks(m);')
    o.append('    }')
    o.append('    if(m.excephalten & m.excepsrc) m.Halt();')
    o.append('  }')
    o.append('  return n;')
    o.append('}')
    o.append('')
    o.append('const AotModule kModule = {0x%08XU, %dU, kCode, Run, Bind, "%s"};' % (base, length, tag))
    o.append('struct Registrar { Registrar() { AotRegister(&kModule); } } g_registrar;')
    o.append('')
    o.append('}  // namespace')
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    open(out, 'w', newline='\n').write('\n'.join(o) + '\n')
    print('%s: %d packets, %d nuances, %d fixups' % (out, len(packets), len(nuances), len(fixups)))


if __name__ == '__main__':
    main()
